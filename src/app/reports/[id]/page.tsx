function AnalysisSection({
  evaluationId,
  configured,
  result,
  generated,
  autoGenerated,
  disabled,
  memoryEnabled,
  fallback,
}: Readonly<{
  evaluationId: string;
  configured: boolean;
  result: RunAnalysisStatus | null;
  generated: boolean;
  autoGenerated: boolean;
  disabled: boolean;
  memoryEnabled: boolean;
  fallback: string;
}>) {
  const unavailableMessage = !configured
    ? "AI analysis is not configured."
    : result && !result.ok
      ? result.message
      : "AI analysis temporarily unavailable.";

  return (
    <DetailSection
      label="MODELLEDGER ANALYSIS"
      title="ModelLedger analysis"
      description="Run-wide interpretation of stored facts, prioritized test evidence, version changes, and related history."
    >
      {!generated ? (
        <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
          <p className="text-sm leading-6 text-slate-600">
            {configured
              ? disabled
                ? "AI analysis generation is turned off for this view."
                : autoGenerated
                  ? "AI analysis is generated for high-priority issues."
                  : fallback
              : "AI analysis is not configured."}
          </p>
          {configured ? (
            <Link
              href={`/reports/${evaluationId}?memory=${memoryEnabled ? "on" : "off"}&ai=on`}
              className="inline-flex h-9 items-center justify-center rounded-md border border-slate-200 bg-white px-3 text-sm font-semibold text-slate-950 transition-colors hover:bg-slate-50 active:translate-y-px"
            >
              Generate Analysis
            </Link>
          ) : null}
        </div>
      ) : !configured || !result || !result.ok ? (
        <p className="text-sm leading-6 text-slate-600">{unavailableMessage}</p>
      ) : (
        <div className="grid gap-3">
          <p className="text-sm leading-6 text-slate-700">
            {result.analysis.executiveSummary}
          </p>
          <p className="text-sm font-semibold text-slate-950">
            Confidence: {result.analysis.confidence}
          </p>
        </div>
      )}
    </DetailSection>
  );
}

function MemoryEvidenceSection({
  evaluationId,
  enabled,
  configured,
  recallGroups,
  memories,
  unavailableOverride = false,
}: Readonly<{
  evaluationId: string;
  enabled: boolean;
  configured: boolean;
  recallGroups: EvaluationDetailRecallGroups | null;
  memories: readonly HindsightRecallMemory[];
  unavailableOverride?: boolean;
}>) {
  const unavailable = unavailableOverride || (recallGroups
    ? [
        recallGroups.similarFailures,
        recallGroups.previousResolutions,
        recallGroups.historicalRegressions,
        recallGroups.relevantVersionChanges,
      ].some((result) => !result.ok)
    : false);
  const visibleMemories = memories.slice(0, 3);

  return (
    <DetailSection
      label="HISTORICAL EVIDENCE"
      title="Historical evidence"
      description="Related stored history and recalled Hindsight memory are evidence, not proof of causation."
    >
      <div className="mb-4 flex flex-wrap items-center gap-2">
        <Link
          href={`/reports/${evaluationId}?memory=off`}
          className={`rounded-sm border px-3 py-1.5 text-sm font-semibold ${
            !enabled
              ? "border-slate-950 bg-slate-950 text-white"
              : "border-slate-200 text-slate-700"
          }`}
        >
          Without Memory
        </Link>
        <Link
          href={`/reports/${evaluationId}?memory=on`}
          className={`rounded-sm border px-3 py-1.5 text-sm font-semibold ${
            enabled
              ? "border-slate-950 bg-slate-950 text-white"
              : "border-slate-200 text-slate-700"
          }`}
        >
          With Memory
        </Link>
      </div>
      {enabled && unavailable && visibleMemories.length > 0 && <p className="mb-3 text-sm text-amber-800">Historical recall is partially unavailable. The evidence below includes the available stored or recalled records.</p>}

      {!enabled ? (
        <p className="text-sm leading-6 text-slate-600">
          Without Memory mode shows only current stored facts and deterministic analysis.
        </p>
      ) : (!configured || unavailable) && visibleMemories.length === 0 ? (
        <p className="text-sm leading-6 text-slate-600">
          Historical memory is temporarily unavailable.
        </p>
      ) : visibleMemories.length === 0 ? (
        <p className="text-sm leading-6 text-slate-600">
          No related historical issue found. This may be a new failure pattern.
        </p>
      ) : (
        <div className="grid gap-3">
          {visibleMemories.map((memory) => (
            <article key={memory.id} className="rounded-md border border-slate-200 p-4">
              <div className="flex flex-wrap items-center gap-2 text-xs font-medium uppercase tracking-[0.08em] text-slate-500">
                <span>{memory.id.startsWith("stored:") ? "Stored history" : "Recalled memory"} · {memory.eventType?.replaceAll("_", " ") ?? "Memory"}</span>
                <span>{memory.version ?? memory.modelVersionId ?? "Version not recorded"}</span>
                <span>{memory.timestamp ? formatDate(memory.timestamp) : "Date not recorded"}</span>
              </div>
              <p className="mt-2 text-sm leading-6 text-slate-700">
                {memory.content}
              </p>
            </article>
          ))}
        </div>
      )}
    </DetailSection>
  );
}

