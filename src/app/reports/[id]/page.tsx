const dateFormatter = new Intl.DateTimeFormat("en", {
  month: "short",
  day: "numeric",
  year: "numeric",
});

function formatDate(value: string) {
  return dateFormatter.format(new Date(value));
}

function formatPercent(value: number | null) {
  return value === null ? "Not recorded" : `${Math.round(value * 100)}%`;
}

function formatNumber(value: number | null | undefined, suffix = "") {
  return typeof value === "number" && Number.isFinite(value)
    ? `${value.toLocaleString()}${suffix}`
    : "Not recorded";
}

function formatCompactNumber(value: number | null | undefined) {
  if (typeof value !== "number" || !Number.isFinite(value)) return "Not recorded";
  if (Math.abs(value) >= 1000) return `${(value / 1000).toFixed(1)}K`;
  return value.toLocaleString();
}

function formatTelemetry(value: number | null, coverage: TelemetryCoverage, formatter = formatCompactNumber) {
  const formatted = formatter(value);
  return value !== null && coverage.recorded < coverage.total ? `${formatted} (partial: ${coverage.recorded}/${coverage.total} tests)` : formatted;
}

function formatCurrency(value: number | null | undefined) {
  return typeof value === "number" && Number.isFinite(value)
    ? `$${value.toFixed(6)}`
    : "Not recorded";
}

function formatDecimal(value: number | null | undefined, digits = 2) {
  return typeof value === "number" && Number.isFinite(value)
    ? value.toFixed(digits)
    : "Not recorded";
}

function formatLatencySeconds(value: number | null | undefined) {
  return typeof value === "number" && Number.isFinite(value)
    ? `${(value / 1000).toFixed(2)}s`
    : "Not recorded";
}

function getRunMode(value: unknown) {
  return (
    typeof value === "object" &&
    value &&
    !Array.isArray(value) &&
    "mode" in value &&
    typeof value.mode === "string"
  )
    ? value.mode
    : "legacy/manual";
}

